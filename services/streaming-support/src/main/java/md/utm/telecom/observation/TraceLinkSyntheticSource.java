package md.utm.telecom.observation;

import com.fasterxml.jackson.databind.JsonNode;
import java.time.Clock;

/** Explicit source resolver for isolated live-synthetic artifacts, never legacy runtime authority. */
public final class TraceLinkSyntheticSource {
    public static final String DATASET = "trace-link-live-synthetic-v1";
    public static final String GENERATOR = "trace-link-minute-generator-v1";
    private final DomainObservationValidator validator;
    public TraceLinkSyntheticSource(Clock clock) throws java.io.IOException { validator = new DomainObservationValidator(clock); }
    public long resolve(JsonNode observation) {
        validator.validate(observation);
        require(observation.path("datasetId").asText().equals(DATASET) && observation.path("sourceResolutionSeconds").asInt() == 60
                && observation.path("revision").asInt() == 0 && observation.path("finalized").asBoolean(), "Wrong live synthetic namespace/resolution");
        require(java.util.Set.of("transport.traffic", "transport.effectiveCapacity", "transport.link.utilization",
                "roaming.registration.success", "mobileData.dns.success", "mobileData.activation.success")
                .contains(observation.path("metricId").asText()), "Metric not generated by this source version");
        String source = observation.path("sourceId").asText();
        require(source.matches(GENERATOR + "-seed-(0|[1-9][0-9]{0,18})"), "Unresolved synthetic source");
        try { return Long.parseLong(source.substring((GENERATOR + "-seed-").length())); }
        catch (NumberFormatException invalid) { throw new IllegalArgumentException("Seed outside signed long", invalid); }
    }
    private static void require(boolean valid, String reason) { if (!valid) throw new IllegalArgumentException(reason); }
}
