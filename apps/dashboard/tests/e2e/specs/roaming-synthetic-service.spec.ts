test('the shared incident queue includes roaming and preserves its three filters',async({page})=>{
  await controlledApi(page);await recordedRoaming(page);const {incident}=nativeIncidentFixture();
  await page.route('**/api/v2/trace-link/incidents?**',route=>route.fulfill({json:{items:[incident],total:1,limit:50,offset:0}}));
  await page.route('**/api/v2/trace-link/incidents/*/workflow',route=>route.fulfill({json:{episodeId:incident.episodeId,id:'workflow',status:'OPEN',version:1,assigneeId:null}}));
  await page.goto('/dashboard#incident-queue');
  const queue=page.locator('.queue-panel');await expect(queue).toBeVisible();
  await queue.getByRole('combobox',{name:'Queue service',exact:true}).selectOption('ROAMING');
  await expect(queue.locator('.queue-item')).toHaveCount(0);
  await expect(queue.locator('.episode-card')).toHaveCount(1);
  await expect(queue.locator('.queue-filters select')).toHaveCount(3);
  await expect(queue.locator('.episode-card')).toContainText('Roaming registration success drop');
  await queue.getByRole('combobox',{name:'State',exact:true}).selectOption('ONGOING');
  await expect(queue.locator('.episode-card')).toHaveCount(0);
});

test('current synthetic roaming continues following completed data after switching metrics',async({page})=>{
  await controlledApi(page);await recordedRoaming(page);
  let end=Math.floor(Date.now()/300000)*300000;
  await page.route('**/api/v2/datasets',route=>route.fulfill({json:[{datasetId:'roaming-demo-v1',from:new Date(end-30*86400000).toISOString(),to:new Date(end).toISOString(),catalogueVersion:'recorded-partners',synthetic:true,archiveReady:true}]}));
  await page.clock.install({time:end});
  await page.goto('/roaming');
  await expect(page.locator('.kpi-summary tbody td:nth-child(2)').first()).toHaveText('98%');
  await page.getByRole('button',{name:'Data session success',exact:true}).click();
  await expect(page).toHaveURL(/follow=latest/);
  await expect(page.locator('[data-chart=roamingDataSrPct] .actual-line')).not.toHaveAttribute('d','');
  const firstEnd=await page.locator('input[type=datetime-local]').nth(1).inputValue();
  end+=300000;await page.clock.fastForward(300000);
  await expect(page.locator('input[type=datetime-local]').nth(1)).not.toHaveValue(firstEnd);
  await expect(page.locator('.kpi-summary tbody td:nth-child(2)').first()).toHaveText('98%');
  await page.goto('/roaming?follow=latest&from=invalid&to='+new Date(end).toISOString());
  await expect(page.getByRole('alert')).toContainText('Invalid roaming context');
});
