  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await card.getByRole('button',{name:'View incident evidence',exact:true}).click();
  const evidence=page.getByRole('dialog',{name:'Incident evidence',exact:true});
