  await expect(page.locator('.roaming-chart .expected-line')).not.toHaveAttribute('d','');
  expect(await page.locator('.traffic-success-bar').count()).toBeGreaterThan(0);
  await expect(page.locator('.recorded-incident-line')).toHaveCount(1);
  await expect(page.locator('.recorded-recovery-line')).toHaveCount(1);
  const card=page.locator('.episode-card').first();
  await expect(card).toContainText('Roaming registration success drop');
  await expect(card).toContainText('RECOVERED');
  await expect(card.getByRole('button',{name:'Acknowledge',exact:true})).toBeEnabled();
